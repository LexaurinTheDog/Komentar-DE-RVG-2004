#!/usr/bin/env python3
"""Reproduce bounded-review hashes and scope checks; not an automated legal review."""
from pathlib import Path
import json, re, hashlib, subprocess, datetime, unicodedata
import xml.etree.ElementTree as E
W=Path(__file__).resolve().parent
IDS='p31 p31a p31b p32 p33 p34 p35 p36 p37 p38 p38a p39 p40 p41 p41a p42 p43 p44 p45 p46'.split()
BASE='4bdd61cf1d9063ee471f741acee1a6c60c2eaa92'
def comments(text):
 return {b.split('\n',1)[0]:b.split('\n',1)[1].strip() for b in re.split(r'^=== ',text,flags=re.M)[1:]}
def sha(s):return hashlib.sha256(s.encode()).hexdigest()
def raw(e):
 if e is None:return ''
 s=e.text or ''
 for c in e:
  if c.tag!='noindex':s+=raw(c)
  s+=c.tail or ''
 return s
def normal(s):return re.sub(r'[\s|]+','',unicodedata.normalize('NFKC',s))
before={};after={}
for p in sorted((W/'commentary').glob('*.md')):
 relative=str(p.relative_to(W))
 old=subprocess.check_output(['git','-C',str(W),'show',BASE+':'+relative],text=True)
 before.update(comments(old));after.update(comments(p.read_text()))
changed=[i for i in before if before[i]!=after[i]]
assert not(set(changed)-set(IDS)), 'Unassigned commentary changed'
assert set(before)==set(after)
units={u['id']:u for u in [json.loads(l) for l in (W/'units.jsonl').read_text().splitlines()]}
P=W/'sources/review-p31-p46-2026-10-20/rvg.xml';root=E.parse(P).getroot()
texts={'p'+n.findtext('metadaten/enbez')[2:].strip():raw(n.find('textdaten/text/Content')) for n in root.findall('norm') if (n.findtext('metadaten/enbez') or '').startswith('§ ')}
checks=[]
for i in IDS:
 a=normal(texts[i]);b=normal(units[i]['text'])
 checks.append({'id':i,'official_xml_character_stream_sha256':sha(a),'parsed_character_stream_sha256':sha(b),'equal':a==b,'commentary_before_sha256':sha(before[i]),'commentary_after_sha256':sha(after[i]),'commentary_changed':i in changed})
assert all(c['equal'] for c in checks)
r={'scope':'technical evidence for independently read bounded substantive review; not legal conclusions generated by this script','base_commit':BASE,'official_xml_path':str(P.relative_to(W)),'official_xml_sha256':hashlib.sha256(P.read_bytes()).hexdigest(),'reviewed_ids':IDS,'checks':checks,'changed_ids':changed,'unchanged_outside_assignment':True,'unassigned_commentary_units_preserved':len(after)-len(IDS),'total_commentary_units':len(after),'all_assigned_texts_match_official_xml':True}
(W/'review-p31-p46-unit-evidence.json').write_text(json.dumps(r,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'assigned':len(IDS),'changed':changed,'unassigned_preserved':r['unassigned_commentary_units_preserved'],'all_texts_match':True}))
